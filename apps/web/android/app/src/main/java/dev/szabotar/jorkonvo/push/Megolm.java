package dev.szabotar.jorkonvo.push;

import java.nio.charset.StandardCharsets;
import java.security.GeneralSecurityException;
import java.security.KeyFactory;
import java.security.MessageDigest;
import java.security.PublicKey;
import java.security.Signature;
import java.security.spec.X509EncodedKeySpec;
import java.util.Arrays;
import javax.crypto.Cipher;
import javax.crypto.Mac;
import javax.crypto.spec.IvParameterSpec;
import javax.crypto.spec.SecretKeySpec;

/**
 * Decrypt-only Megolm (m.megolm.v1.aes-sha2), so a push for an encrypted
 * room can show the real text without the WebView's rust-crypto store.
 *
 * Input is what the app exports (matrix-js-sdk exportRoomKeys, see
 * src/lib/push/nativeStore.ts): an "exported session key"
 *
 *   0x01 | u32 BE message index | R0 R1 R2 R3 (4 x 32 bytes) | Ed25519 key (32)
 *
 * and a Megolm message
 *
 *   0x03 | protobuf{ 0x08 varint index, 0x12 varint len ciphertext } | MAC (8) | Ed25519 signature (64)
 *
 * Per the Megolm spec (and libolm's megolm_advance_to): advance the ratchet
 * to the message index, HKDF-SHA256(ratchet, "MEGOLM_KEYS") -> AES-256 key |
 * HMAC key | IV, check the truncated HMAC, AES-256-CBC/PKCS7 decrypt. The
 * Ed25519 signature is verified where the platform has Ed25519 (Android 13+,
 * any JVM 15+); below that only the MAC is checked - it still proves the
 * message was made with this session's key, the signature additionally ties
 * it to the sending device (the app re-verifies everything when opened).
 *
 * Tested against vectors generated by vodozemac (MegolmTest).
 */
public final class Megolm {

    public static final class DecryptionException extends Exception {
        public DecryptionException(String message) {
            super(message);
        }
    }

    private static final int EXPORTED_KEY_LENGTH = 1 + 4 + 128 + 32;
    private static final int MAC_LENGTH = 8;
    private static final int SIGNATURE_LENGTH = 64;
    private static final byte[] ED25519_X509_PREFIX = {
        0x30, 0x2a, 0x30, 0x05, 0x06, 0x03, 0x2b, 0x65, 0x70, 0x03, 0x21, 0x00,
    };

    private Megolm() {}

    /** Returns the decrypted plaintext (the event JSON). */
    public static String decrypt(String exportedSessionKeyB64, String ciphertextB64) throws DecryptionException {
        byte[] key = unbase64(exportedSessionKeyB64);
        if (key.length != EXPORTED_KEY_LENGTH || key[0] != 0x01) {
            throw new DecryptionException("not an exported Megolm session key");
        }
        long firstIndex = readU32(key, 1);
        byte[][] ratchet = new byte[4][];
        for (int j = 0; j < 4; j++) ratchet[j] = Arrays.copyOfRange(key, 5 + 32 * j, 5 + 32 * (j + 1));
        byte[] signingKey = Arrays.copyOfRange(key, 5 + 128, EXPORTED_KEY_LENGTH);

        byte[] msg = unbase64(ciphertextB64);
        if (msg.length < 1 + MAC_LENGTH + SIGNATURE_LENGTH || msg[0] != 0x03) {
            throw new DecryptionException("not a Megolm v3 message");
        }
        int macEnd = msg.length - SIGNATURE_LENGTH;
        int bodyEnd = macEnd - MAC_LENGTH;

        // Protobuf body: message index (field 1, varint) + ciphertext (field 2, bytes).
        long index = -1;
        byte[] ciphertext = null;
        int[] pos = {1};
        while (pos[0] < bodyEnd) {
            long tag = readVarint(msg, pos, bodyEnd);
            if (tag == 0x08) {
                index = readVarint(msg, pos, bodyEnd);
            } else if (tag == 0x12) {
                long len = readVarint(msg, pos, bodyEnd);
                if (len < 0 || pos[0] + len > bodyEnd) throw new DecryptionException("bad ciphertext length");
                ciphertext = Arrays.copyOfRange(msg, pos[0], pos[0] + (int) len);
                pos[0] += (int) len;
            } else {
                throw new DecryptionException("unexpected protobuf tag " + tag);
            }
        }
        if (index < 0 || ciphertext == null) throw new DecryptionException("incomplete message");
        if (index < firstIndex) {
            throw new DecryptionException("message index " + index + " is before the known index " + firstIndex);
        }

        try {
            advance(ratchet, firstIndex, index);
            byte[] material = new byte[128];
            for (int j = 0; j < 4; j++) System.arraycopy(ratchet[j], 0, material, 32 * j, 32);
            byte[] keys = hkdfSha256(material, "MEGOLM_KEYS".getBytes(StandardCharsets.US_ASCII), 80);
            byte[] aesKey = Arrays.copyOfRange(keys, 0, 32);
            byte[] macKey = Arrays.copyOfRange(keys, 32, 64);
            byte[] iv = Arrays.copyOfRange(keys, 64, 80);

            byte[] mac = hmacSha256(macKey, Arrays.copyOfRange(msg, 0, bodyEnd));
            if (!MessageDigest.isEqual(Arrays.copyOf(mac, MAC_LENGTH), Arrays.copyOfRange(msg, bodyEnd, macEnd))) {
                throw new DecryptionException("MAC mismatch");
            }
            verifySignatureIfSupported(signingKey, Arrays.copyOfRange(msg, 0, macEnd), Arrays.copyOfRange(msg, macEnd, msg.length));

            Cipher aes = Cipher.getInstance("AES/CBC/PKCS5Padding");
            aes.init(Cipher.DECRYPT_MODE, new SecretKeySpec(aesKey, "AES"), new IvParameterSpec(iv));
            return new String(aes.doFinal(ciphertext), StandardCharsets.UTF_8);
        } catch (GeneralSecurityException e) {
            throw new DecryptionException("crypto failure: " + e.getMessage());
        }
    }

    /** libolm megolm_advance_to: R(j) rehashes R(j..3) whenever its byte of the counter changes. */
    static void advance(byte[][] r, long counter, long target) throws GeneralSecurityException {
        for (int j = 0; j < 4; j++) {
            int shift = (3 - j) * 8;
            long mask = (0xFFFFFFFFL << shift) & 0xFFFFFFFFL;
            long steps = ((target >>> shift) - (counter >>> shift)) & 0xFF;
            if (steps == 0) {
                // Only a wrap-around (target < counter) needs a full lap; never the case
                // here because target >= counter is checked above.
                continue;
            }
            // All but the last step only bump R(j) itself...
            while (steps > 1) {
                r[j] = hmacSha256(r[j], new byte[] {(byte) j});
                steps--;
            }
            // ...the last one also re-seeds R(j+1)..R(3) from it (R(j) last).
            byte[] seed = r[j];
            for (int k = 3; k >= j; k--) r[k] = hmacSha256(seed, new byte[] {(byte) k});
            counter = target & mask;
        }
    }

    static byte[] hkdfSha256(byte[] ikm, byte[] info, int length) throws GeneralSecurityException {
        // Zero-length salt == HashLen zero bytes (RFC 5869); vodozemac's salt of a
        // single 0x00 byte is the same HMAC key once padded.
        byte[] prk = hmacSha256(new byte[32], ikm);
        byte[] out = new byte[length];
        byte[] t = new byte[0];
        int filled = 0;
        for (int i = 1; filled < length; i++) {
            Mac mac = Mac.getInstance("HmacSHA256");
            mac.init(new SecretKeySpec(prk, "HmacSHA256"));
            mac.update(t);
            mac.update(info);
            mac.update((byte) i);
            t = mac.doFinal();
            int n = Math.min(t.length, length - filled);
            System.arraycopy(t, 0, out, filled, n);
            filled += n;
        }
        return out;
    }

    static byte[] hmacSha256(byte[] key, byte[] data) throws GeneralSecurityException {
        Mac mac = Mac.getInstance("HmacSHA256");
        mac.init(new SecretKeySpec(key, "HmacSHA256"));
        return mac.doFinal(data);
    }

    private static void verifySignatureIfSupported(byte[] publicKey, byte[] signed, byte[] signature)
        throws GeneralSecurityException, DecryptionException {
        Signature verifier;
        PublicKey key;
        try {
            byte[] x509 = new byte[ED25519_X509_PREFIX.length + publicKey.length];
            System.arraycopy(ED25519_X509_PREFIX, 0, x509, 0, ED25519_X509_PREFIX.length);
            System.arraycopy(publicKey, 0, x509, ED25519_X509_PREFIX.length, publicKey.length);
            key = KeyFactory.getInstance("Ed25519").generatePublic(new X509EncodedKeySpec(x509));
            verifier = Signature.getInstance("Ed25519");
        } catch (GeneralSecurityException unsupported) {
            return; // No Ed25519 provider (Android < 13): MAC-only, see class comment.
        }
        verifier.initVerify(key);
        verifier.update(signed);
        if (!verifier.verify(signature)) throw new DecryptionException("bad signature");
    }

    private static long readU32(byte[] b, int off) {
        return ((b[off] & 0xFFL) << 24) | ((b[off + 1] & 0xFFL) << 16) | ((b[off + 2] & 0xFFL) << 8) | (b[off + 3] & 0xFFL);
    }

    private static long readVarint(byte[] b, int[] pos, int end) throws DecryptionException {
        long result = 0;
        for (int shift = 0; shift < 64; shift += 7) {
            if (pos[0] >= end) throw new DecryptionException("truncated varint");
            byte x = b[pos[0]++];
            result |= (long) (x & 0x7F) << shift;
            if ((x & 0x80) == 0) return result;
        }
        throw new DecryptionException("varint too long");
    }

    /**
     * Standard base64, padding optional (Matrix sends it unpadded). Hand-rolled
     * because java.util.Base64 needs API 26 (minSdk is 24) and android.util.Base64
     * doesn't exist in plain-JVM unit tests.
     */
    static byte[] unbase64(String s) throws DecryptionException {
        String in = s.trim();
        int end = in.length();
        while (end > 0 && in.charAt(end - 1) == '=') end--;
        byte[] out = new byte[end * 3 / 4];
        int acc = 0;
        int bits = 0;
        int o = 0;
        for (int i = 0; i < end; i++) {
            char c = in.charAt(i);
            int v;
            if (c >= 'A' && c <= 'Z') v = c - 'A';
            else if (c >= 'a' && c <= 'z') v = c - 'a' + 26;
            else if (c >= '0' && c <= '9') v = c - '0' + 52;
            else if (c == '+' || c == '-') v = 62;
            else if (c == '/' || c == '_') v = 63;
            else throw new DecryptionException("bad base64");
            acc = (acc << 6) | v;
            bits += 6;
            if (bits >= 8) {
                bits -= 8;
                out[o++] = (byte) (acc >> bits);
            }
        }
        if (end % 4 == 1) throw new DecryptionException("bad base64 length");
        return o == out.length ? out : Arrays.copyOf(out, o);
    }
}
