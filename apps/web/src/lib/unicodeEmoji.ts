export const UNICODE_EMOJI: UnicodeEmoji[] = RAW.map(([code, char, group, kw]) => ({ code, char, group, kw }));

const BY_CODE = new Map(UNICODE_EMOJI.map((e) => [e.code, e]));

export function emojiForShortcode(code: string): string | null {
  return BY_CODE.get(code.replace(/^:|:$/g, ""))?.char ?? null;
}

/** Fuzzy-ish match on shortcode + keywords, code-prefix matches ranked first. */
export function searchUnicodeEmoji(query: string, limit = 20): UnicodeEmoji[] {
  const q = query.trim().toLowerCase();
  if (!q) return [];
  const starts: UnicodeEmoji[] = [];
  const contains: UnicodeEmoji[] = [];
  for (const e of UNICODE_EMOJI) {
    if (e.code.startsWith(q)) starts.push(e);
    else if (e.code.includes(q) || (e.kw && e.kw.includes(q))) contains.push(e);
    if (starts.length >= limit) break;
  }
  return [...starts, ...contains].slice(0, limit);
}

