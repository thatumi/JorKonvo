import { EventType, type MatrixClient, type Room, RoomType } from "matrix-js-sdk";
import { getOwningSpace } from "./rooms.js";

/**
 * JorKonvo's own domain for invite links, in place of matrix.to. matrix.to
 * is a third party JorKonvo's developer doesn't control, so Android/iOS
 * can only ever offer a disambiguation dialog for it (no way to prove
 * domain ownership for a verified App Link / Universal Link). A link
 * minted on this domain can be verified (see
 * apps/web/public/.well-known/{assetlinks.json,apple-app-site-association})
 * so tapping it opens JorKonvo directly, no chooser.
 */
export const INVITE_LINK_DOMAIN = "jorkonvo.szabotar.dev";

function serverNameOf(userId: string | null | undefined): string | null {
  if (!userId) return null;
  const idx = userId.indexOf(":");
  return idx === -1 ? null : userId.slice(idx + 1);
}

/**
 * Candidate servers to route a room-id-based matrix.to link through
 * (the `via` query params) - the room creator's server plus the
 * current user's own, deduplicated. Not exhaustive (Element's own
 * heuristic also weighs in servers with the most joined power), but
 * functionally enough for the link to actually resolve.
 */
function getViaServers(client: MatrixClient, room: Room): string[] {
  const servers = new Set<string>();
  const ownServer = serverNameOf(client.getUserId());
  if (ownServer) servers.add(ownServer);
  const createEvent = room.currentState.getStateEvents(EventType.RoomCreate, "");
  const creatorServer = serverNameOf(createEvent?.getSender());
  if (creatorServer) servers.add(creatorServer);
  return [...servers];
}

function buildFragment(target: string, viaServers: string[], spaceId?: string): string {
  const params = viaServers.map((v) => `via=${encodeURIComponent(v)}`);
  if (spaceId) params.push(`space=${encodeURIComponent(spaceId)}`);
  const query = params.join("&");
  return `${encodeURIComponent(target)}${query ? `?${query}` : ""}`;
}

/**
 * A shareable JorKonvo invite link for the room - its canonical alias if it
 * has one, else the room id + via servers. Same matrix.to fragment shape
 * (`#/<target>?via=...`), just served from a domain JorKonvo can verify
 * ownership of, so the native apps can register it as a real App
 * Link/Universal Link instead of a matrix.to disambiguation dialog.
 *
 * If `room` is itself a joined channel (not a space) that belongs to a
 * space, the link also carries a `space=<spaceId>` hint (see
 * parseInviteLink) - a plain room-only link is useless to someone who isn't
 * already a space member: this app's rooms default to a `restricted`
 * join_rule keyed on space membership (see room-admin.ts createRoom), so
 * joining the room directly just fails outright for them. The `space` hint
 * is what lets the join flow join the space FIRST (which a non-member CAN
 * always do, space join_rule permitting) and only then retry the room -
 * "click a link, you're in", not "click a link, get a permissions error"
 * (a real bug hit live 2026-09-16: a room-only link left a non-space-member
 * with no path in at all beyond a raw "you need an invite" message).
 */
export function getRoomInviteLink(client: MatrixClient, room: Room): string {
  const alias = room.getCanonicalAlias();
  const owningSpace = getOwningSpace(client, room.roomId);
  const spaceId = owningSpace ? owningSpace.roomId : undefined;
  const fragment = alias
    ? buildFragment(alias, [], spaceId)
    : buildFragment(room.roomId, getViaServers(client, room), spaceId);
  return `https://${INVITE_LINK_DOMAIN}/join#/${fragment}`;
}

/**
 * Parses a pasted or opened invite link into its room id/alias target,
 * via-server hints, and (if the link was minted for a channel inside a
 * space) the owning space's room id. Accepts three equivalent shapes:
 * - JorKonvo's own `https://jorkonvo.szabotar.dev/join#/...` (Android App
 *   Link / iOS Universal Link target)
 * - `jorkonvo://join#/...` (the iOS custom-scheme fallback registered
 *   alongside the Universal Link, for when that can't verify - see
 *   Info.plist CFBundleURLTypes)
 * - a plain matrix.to one (`https://matrix.to/#/...`, still valid and still
 *   generated by every other Matrix client - never carries a `space` hint,
 *   since that's JorKonvo's own addition)
 * Returns null if the input doesn't look like any of these (e.g. a bare
 * room id/alias someone typed directly, which callers should just pass
 * straight through to the SDK instead).
 */
export function parseInviteLink(input: string): { target: string; viaServers: string[]; spaceId?: string } | null {
  const trimmed = input.trim();
  const escapedDomain = INVITE_LINK_DOMAIN.replace(/\./g, "\\.");
  const match =
    /^https?:\/\/matrix\.to\/#\/([^?]+)(?:\?(.*))?$/.exec(trimmed) ??
    new RegExp(`^https?://${escapedDomain}/join/?#/([^?]+)(?:\\?(.*))?$`).exec(trimmed) ??
    /^jorkonvo:\/\/join\/?#\/([^?]+)(?:\?(.*))?$/.exec(trimmed);
  if (!match) return null;
  const target = decodeURIComponent(match[1]!);
  const params = new URLSearchParams(match[2] ?? "");
  const viaServers = [...params.entries()].filter(([key]) => key === "via").map(([, value]) => value);
  const spaceId = params.get("space") ?? undefined;
  return { target, viaServers, spaceId };
}

export interface InviteLinkPreview {
  spaceId?: string;
  spaceName?: string;
  spaceAvatarMxcUrl?: string;
  spaceMemberCount?: number;
  targetRoomId: string;
  targetName?: string;
  targetAvatarMxcUrl?: string;
  targetMemberCount?: number;
  targetIsSpace: boolean;
}

/**
 * Best-effort "who/what is this invite link actually for" lookup, for
 * rendering a Discord-style invite card under a message instead of a bare
 * link (InviteLinkCard.tsx) - never throws, returns null on any failure
 * (private target, unsupported server, network error) so the card can fall
 * back to a plain "Join" button with no name/avatar rather than being
 * blocked by it.
 *
 * Two paths: if the target (or its owning space) is already known to this
 * client - already joined, or seen via a previous hierarchy/directory
 * fetch - that's used directly, no network round-trip. Otherwise, falls
 * back to the spec's `/hierarchy` endpoint (MSC2946, same one
 * getSpaceHierarchy in rooms.ts uses), rooted at the space if the link
 * carries one, else at the target itself. Synapse generally allows this
 * for a *publicly joinable* space/room even to a non-member - which is
 * exactly this app's default for newly created spaces as of 2026-09-16 -
 * so this works precisely for the case that matters most (a real invite
 * link to a server you're not in yet), while degrading gracefully for an
 * invite-only one you'd need to already have access to preview anyway.
 */
export async function previewInviteLink(
  client: MatrixClient,
  parsed: { target: string; viaServers: string[]; spaceId?: string },
): Promise<InviteLinkPreview | null> {
  const knownTarget = client.getRoom(parsed.target);
  const knownSpace = parsed.spaceId ? client.getRoom(parsed.spaceId) : null;
  if (knownTarget || knownSpace) {
    return {
      spaceId: parsed.spaceId,
      spaceName: knownSpace?.name,
      spaceAvatarMxcUrl: knownSpace?.getMxcAvatarUrl() ?? undefined,
      targetRoomId: parsed.target,
      targetName: knownTarget?.name,
      targetAvatarMxcUrl: knownTarget?.getMxcAvatarUrl() ?? undefined,
      targetMemberCount: knownTarget?.getJoinedMemberCount(),
      targetIsSpace: knownTarget ? knownTarget.getType() === RoomType.Space : false,
    };
  }

  const rootId = parsed.spaceId ?? parsed.target;
  try {
    const page = await client.getRoomHierarchy(rootId, 50, undefined, false);
    const rootEntry = page.rooms.find((r) => r.room_id === rootId);
    const targetEntry = page.rooms.find((r) => r.room_id === parsed.target);
    if (!rootEntry && !targetEntry) return null;
    const targetIsRoot = parsed.target === rootId;
    return {
      spaceId: parsed.spaceId,
      spaceName: rootEntry?.name ?? rootEntry?.canonical_alias,
      spaceAvatarMxcUrl: rootEntry?.avatar_url,
      spaceMemberCount: rootEntry?.num_joined_members,
      targetRoomId: parsed.target,
      targetName: targetEntry?.name ?? targetEntry?.canonical_alias ?? (targetIsRoot ? rootEntry?.name : undefined),
      targetAvatarMxcUrl: targetEntry?.avatar_url ?? (targetIsRoot ? rootEntry?.avatar_url : undefined),
      targetMemberCount: targetEntry?.num_joined_members ?? (targetIsRoot ? rootEntry?.num_joined_members : undefined),
      targetIsSpace: targetIsRoot || targetEntry?.room_type === RoomType.Space,
    };
  } catch {
    return null;
  }
}
