import { describe, expect, it } from "vitest";
import { getRoomInviteLink, parseInviteLink, previewInviteLink } from "../../../packages/matrix-core/src/inviteLinks.js";
import { FakeClient, FakeRoom } from "../../helpers/fakes.js";

/** FakeClient plus a scriptable getRoomHierarchy - previewInviteLink's only network-ish dependency. */
class HierarchyClient extends FakeClient {
  hierarchyRooms: {
    room_id: string;
    name?: string;
    canonical_alias?: string;
    avatar_url?: string;
    num_joined_members: number;
    room_type?: string;
  }[] = [];
  hierarchyShouldThrow = false;

  getRoomHierarchy(): Promise<{ rooms: typeof this.hierarchyRooms; next_batch?: string }> {
    if (this.hierarchyShouldThrow) return Promise.reject(new Error("M_FORBIDDEN"));
    return Promise.resolve({ rooms: this.hierarchyRooms });
  }
}

describe("getRoomInviteLink", () => {
  it("uses the canonical alias when the room has one", () => {
    const room = new FakeRoom({ canonicalAlias: "#general:test" });
    const client = new FakeClient({ userId: "@me:test" });
    expect(getRoomInviteLink(client as never, room as never)).toBe(
      "https://jorkonvo.szabotar.dev/join#/%23general%3Atest",
    );
  });

  it("falls back to room id + via servers (own + creator server, deduped)", () => {
    const room = new FakeRoom({
      roomId: "!abc:other",
      state: { "m.room.create|": {} },
      stateSenders: { "m.room.create|": "@founder:creator" },
    });
    const client = new FakeClient({ userId: "@me:test" });
    const link = getRoomInviteLink(client as never, room as never);
    expect(link).toContain("https://jorkonvo.szabotar.dev/join#/!abc%3Aother?");
    expect(link).toContain("via=test");
    expect(link).toContain("via=creator");
  });

  it("emits a single via when creator and current user share a server", () => {
    const room = new FakeRoom({
      roomId: "!abc:test",
      state: { "m.room.create|": {} },
      stateSenders: { "m.room.create|": "@founder:test" },
    });
    const client = new FakeClient({ userId: "@me:test" });
    const link = getRoomInviteLink(client as never, room as never);
    expect(link.match(/via=/g)).toHaveLength(1);
  });
});

describe("getRoomInviteLink - space hint (2026-09-16 fix)", () => {
  it("includes a space= hint when the room belongs to a joined space", () => {
    const room = new FakeRoom({ roomId: "!chan:test", canonicalAlias: null });
    const space = new FakeRoom({
      roomId: "!space:test",
      isSpace: true,
      state: { "m.space.child|!chan:test": { via: ["test"] } },
    });
    const client = new FakeClient({ userId: "@me:test", rooms: [room, space] });
    const link = getRoomInviteLink(client as never, room as never);
    expect(link).toContain("space=!space%3Atest");
  });

  it("omits the space hint for a room with no owning space (e.g. the space itself, or an ungrouped room)", () => {
    const room = new FakeRoom({ roomId: "!lonely:test" });
    const client = new FakeClient({ userId: "@me:test", rooms: [room] });
    const link = getRoomInviteLink(client as never, room as never);
    expect(link).not.toContain("space=");
  });
});

describe("parseInviteLink", () => {
  it("round-trips a link generated by getRoomInviteLink (alias)", () => {
    const room = new FakeRoom({ canonicalAlias: "#general:test" });
    const client = new FakeClient({ userId: "@me:test" });
    const link = getRoomInviteLink(client as never, room as never);
    expect(parseInviteLink(link)).toEqual({ target: "#general:test", viaServers: [] });
  });

  it("round-trips a link generated by getRoomInviteLink (room id + via)", () => {
    const room = new FakeRoom({
      roomId: "!abc:other",
      state: { "m.room.create|": {} },
      stateSenders: { "m.room.create|": "@founder:creator" },
    });
    const client = new FakeClient({ userId: "@me:test" });
    const link = getRoomInviteLink(client as never, room as never);
    const parsed = parseInviteLink(link);
    expect(parsed?.target).toBe("!abc:other");
    expect(parsed?.viaServers.sort()).toEqual(["creator", "test"]);
  });

  it("still parses a plain matrix.to link from another Matrix client", () => {
    expect(parseInviteLink("https://matrix.to/#/%23room%3Aserver?via=server")).toEqual({
      target: "#room:server",
      viaServers: ["server"],
    });
  });

  it("parses the iOS custom-scheme fallback", () => {
    expect(parseInviteLink("jorkonvo://join#/!abc%3Aserver")).toEqual({
      target: "!abc:server",
      viaServers: [],
    });
  });

  it("returns null for a bare room id/alias (not a link)", () => {
    expect(parseInviteLink("#general:test")).toBeNull();
    expect(parseInviteLink("!abc:test")).toBeNull();
  });

  it("extracts the space hint (2026-09-16 fix)", () => {
    const parsed = parseInviteLink("https://jorkonvo.szabotar.dev/join#/!chan%3Atest?via=test&space=!space%3Atest");
    expect(parsed).toEqual({ target: "!chan:test", viaServers: ["test"], spaceId: "!space:test" });
  });

  it("has no space hint on a plain matrix.to link (JorKonvo-only addition)", () => {
    const parsed = parseInviteLink("https://matrix.to/#/%23room%3Aserver");
    expect(parsed?.spaceId).toBeUndefined();
  });
});

describe("previewInviteLink (2026-09-16, for the Discord-style invite card)", () => {
  it("fetches the space's own name/avatar/member count via the hierarchy root entry, keyed on the space hint", async () => {
    const client = new HierarchyClient();
    client.hierarchyRooms = [
      { room_id: "!space:test", name: "My Server", avatar_url: "mxc://test/space", num_joined_members: 12 },
      { room_id: "!chan:test", name: "general", num_joined_members: 5 },
    ];
    const preview = await previewInviteLink(client as never, {
      target: "!chan:test",
      viaServers: [],
      spaceId: "!space:test",
    });
    expect(preview).toEqual({
      spaceId: "!space:test",
      spaceName: "My Server",
      spaceAvatarMxcUrl: "mxc://test/space",
      spaceMemberCount: 12,
      targetRoomId: "!chan:test",
      targetName: "general",
      targetAvatarMxcUrl: undefined,
      targetMemberCount: 5,
      targetIsSpace: false,
    });
  });

  it("falls back to the root entry's own name when there's no space hint and the target IS the hierarchy root (a space-only link)", async () => {
    const client = new HierarchyClient();
    client.hierarchyRooms = [{ room_id: "!space:test", name: "My Server", num_joined_members: 3 }];
    const preview = await previewInviteLink(client as never, { target: "!space:test", viaServers: [] });
    expect(preview?.targetName).toBe("My Server");
    expect(preview?.targetIsSpace).toBe(true);
  });

  it("returns null (not throw) when the hierarchy fetch fails - private target, e.g.", async () => {
    const client = new HierarchyClient();
    client.hierarchyShouldThrow = true;
    const preview = await previewInviteLink(client as never, {
      target: "!chan:test",
      viaServers: [],
      spaceId: "!space:test",
    });
    expect(preview).toBeNull();
  });

  it("returns null when the hierarchy responds but contains neither the root nor the target (unexpected shape, not a hard error)", async () => {
    const client = new HierarchyClient();
    client.hierarchyRooms = [{ room_id: "!unrelated:test", num_joined_members: 1 }];
    const preview = await previewInviteLink(client as never, { target: "!chan:test", viaServers: [], spaceId: "!space:test" });
    expect(preview).toBeNull();
  });
});
